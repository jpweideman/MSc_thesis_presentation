"""Split the exact thesis count results into baseline and mean matched comparisons."""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = root.parent / 'MSc_thesis/tables/count_prediction.tex'
analysis = root.parent / 'BNN-EDL/results/count_prediction.tex'
assert source.read_bytes() == analysis.read_bytes()
records = []
for line in source.read_text().splitlines():
    if 'Cold initialisation' in line:
        initialisation = 'cold'
    if 'Warm initialisation' in line:
        initialisation = 'warm'
    if line.startswith(('M-BNN &', 'DM-eBNN &')):
        cells = [part.strip() for part in line.removesuffix('\\\\').split('&')]
        records.append((initialisation, cells))

def two_lines(cell):
    mean, spread = cell.split(r'\,')
    return r'\shortstack{' + mean + r'\\' + spread + '}'

baseline_rows, control_rows = [], []
for start in ['cold', 'warm']:
    if baseline_rows:
        baseline_rows.append(r'\midrule')
        control_rows.append(r'\midrule')
    baseline = next(row for init, row in records if init == start and row[0] == 'M-BNN')
    for mode in ['50', '200']:
        fitted = next(row for init, row in records if init == start and row[0] == 'DM-eBNN' and row[1] == mode)
        baseline_rows.append(' & '.join([start, mode, two_lines(baseline[4]), two_lines(fitted[4])]) + r' \\')
        control_rows.append(' & '.join([start, mode, two_lines(fitted[4]), two_lines(fitted[5])]) + r' \\')

def write_table(name, first_model, second_model, rows):
    header = (r'Initialisation & \shortstack{DM-eBNN\\prior mode} & '
              + r'\shortstack{' + first_model + r'\\count NLL} & '
              + r'\shortstack{' + second_model + r'\\count NLL}')
    text = '% Generated by scripts/build_count_prediction_comparisons.py from unchanged thesis cells.\n'
    text += r'\begin{tabular}{lccc}' + '\n' + r'\toprule' + '\n'
    text += header + r' \\' + '\n' + r'\midrule' + '\n'
    text += '\n'.join(rows) + '\n' + r'\bottomrule' + '\n' + r'\end{tabular}' + '\n'
    (root / 'tables' / name).write_text(text)

write_table('count_baseline_comparison.tex', 'M-BNN', 'DM-eBNN', baseline_rows)
write_table('count_mean_matched_comparison.tex', 'DM-eBNN', 'Mean matched control', control_rows)
