# Two class illustration. All distributions have mean vector (0.5, 0.5).
# Thesis eq:dirichlet-density and eq:aleatoric-as-function-of-total-concentration.
prob = np.linspace(.001, .999, 500)
fig, axs = plt.subplots(1, 2, figsize=(10.6, 3.25), gridspec_kw={'wspace': .35})
for total, color in [(4, BLUE), (40, GREEN)]:
    axs[0].plot(prob, beta.pdf(prob, total/2, total/2), color=color, lw=2.6,
                label=rf'$\alpha_0={total}$')
axs[0].axvline(.5, color=GREY, ls=':', lw=1.2)
axs[0].set(xlabel=r'Class probability $\pi_1$', ylabel='Density', title='The mean stays fixed')
axs[0].legend(loc='upper left', fontsize=12)
totals = np.geomspace(2.05, 100, 400)
aleatoric = digamma(totals+1)-digamma(totals/2+1)
entropy = np.log(2)
axs[1].plot(totals, aleatoric, color=BLUE, lw=2.6, label='Aleatoric')
axs[1].plot(totals, entropy-aleatoric, color=ORANGE, lw=2.6, label='Distributional')
axs[1].axhline(entropy, color=GREY, ls=':', lw=1.3, label='Their sum')
axs[1].set(xlabel=r'Total concentration parameter $\alpha_0$', ylabel='Uncertainty in nats',
           title='The allocation changes', xscale='log', ylim=(0,.79))
axs[1].legend(loc='center right', fontsize=11)
save(fig, 'mean_and_concentration')

