figures, tables = root / 'figures', root / 'tables'
figures.mkdir(exist_ok=True)
tables.mkdir(exist_ok=True)
GREEN, BLUE, ORANGE, GREY = '#00883a', '#326a9f', '#bb741d', '#777777'
