# Numerical slide tables preserve the exact reported cells and seed ranges.
def two_lines(cell):
    if r'\,' in cell:
        mean,seed_range=cell.split(r'\,',1)
        return r'\shortstack{'+mean+r'\\'+seed_range+'}'
    return cell

comparison_rows=[]
for start,mode in [('Cold','50'),('Cold','200'),('Warm','50'),('Warm','200')]:
    baseline=next(r for s,r in records if s==start and r[0]=='M-BNN')
    fitted=next(r for s,r in records if s==start and r[0]=='DM-eBNN' and r[1]==mode)
    comparison_rows.append(' & '.join([start.lower(),mode]+[two_lines(c) for c in [baseline[4],fitted[4],fitted[5]]])+r' \\')
tabular('count_comparison_slide.tex',r'initialisation & \shortstack{Gamma prior\\mode} & \shortstack{M-BNN\\count NLL} & \shortstack{DM-eBNN\\count NLL} & \shortstack{mean matched\\control NLL}',comparison_rows,'lcccc')

